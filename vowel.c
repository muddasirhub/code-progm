#include <stdio.h>
#include <stdlib.h>

int main()
{
    system("clear");

    char choice;

    printf("Enter Character ");
    scanf("%c", &choice);

    switch (choice)
    {
    case 'a':

    case 'e':

    case 'i':

    case 'o':

    case 'u':

    case 'A':

    case 'E':

    case 'I':

    case 'O':

    case 'U':
        printf("It Is Vowel\n");

        break;

    default:
        printf("It Is Consonant\n");
    }

    return 0;
}